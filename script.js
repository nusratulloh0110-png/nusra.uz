let currentPendingLang = '';
let currentLang = 'ru';
let logQueue = Promise.resolve();
let logCounter = 0;
let terminalLoaded = false;

function wait(ms) {
    return new Promise(resolve => setTimeout(resolve, ms));
}

function sanitizeInput(value) {
    return String(value || '').replace(/[<>]/g, '').trim();
}

function formatBudget(lang, total) {
    if (lang === 'ru') return 'от $' + total;
    if (lang === 'uz') return '$' + total + ' dan';
    return 'FROM $' + total;
}

function showToast(messageKey, type) {
    const toast = document.getElementById('siteToast');
    const messageNode = document.getElementById('toastMessage');
    const icon = toast ? toast.querySelector('.toast-icon') : null;
    const dict = translations[currentLang] || translations.ru;
    if (!toast || !messageNode) return;

    messageNode.textContent = dict[messageKey] || translations.ru[messageKey] || '';
    toast.classList.remove('success', 'error', 'show');
    toast.classList.add(type);
    if (icon) {
        icon.className = 'fas toast-icon ' + (type === 'success' ? 'fa-check-circle' : 'fa-circle-exclamation');
    }

    requestAnimationFrame(() => toast.classList.add('show'));
    window.clearTimeout(showToast.timer);
    showToast.timer = window.setTimeout(() => toast.classList.remove('show'), 2600);
}

function setLangButtons(lang) {
    document.querySelectorAll('.lang-switch .lang-btn').forEach(btn => {
        btn.classList.toggle('active-lang', btn.textContent.trim().toLowerCase() === lang);
    });
    document.querySelectorAll('.lang-switch-mobile .lang-btn').forEach(btn => {
        btn.classList.toggle('active-lang', btn.textContent.trim().toLowerCase() === lang);
    });
}

function applyLang(lang) {
    currentLang = lang;
    localStorage.setItem('nusraLang', lang);
    const dict = translations[lang] || translations.ru;

    document.documentElement.lang = lang === 'ai' ? 'en' : lang;
    document.querySelectorAll('[data-key]').forEach(node => {
        const key = node.getAttribute('data-key');
        if (dict[key]) {
            node.innerHTML = dict[key];
        }
    });

    const nameInput = document.getElementById('clientName');
    const phoneInput = document.getElementById('clientPhone');
    const commentInput = document.getElementById('clientComment');
    if (nameInput) nameInput.placeholder = dict.placeholderName;
    if (phoneInput) phoneInput.placeholder = dict.placeholderPhone;
    if (commentInput) commentInput.placeholder = dict.placeholderComment;

    updateServicePriceLabels();
    calculateTotal();
    setLangButtons(lang);
}

function updateServicePriceLabels() {
    document.querySelectorAll('.srv-price[data-base-price]').forEach(node => {
        const price = Number(node.dataset.basePrice || 0);
        node.textContent = formatBudget(currentLang, price);
    });
}

function calculateTotal() {
    const totalNode = document.getElementById('totalPrice');
    const selectedService = document.querySelector('input[name="projectType"]:checked');
    const options = document.querySelectorAll('.feature-calc');
    if (!totalNode || !selectedService) return;

    let total = Number(selectedService.value || 0);
    options.forEach(option => {
        if (option.checked) total += Number(option.value || 0);
    });

    totalNode.textContent = formatBudget(currentLang, total);
}

function scrollTerminalToBottom() {
    const terminal = document.getElementById('sysTerminal');
    if (terminal) terminal.scrollTop = terminal.scrollHeight;
}

async function typeLogLine(message, type) {
    const terminal = document.getElementById('sysTerminal');
    if (!terminal) return;

    const line = document.createElement('p');
    line.className = type || 'sys-msg';
    line.dataset.logId = String(++logCounter);
    terminal.appendChild(line);

    for (const char of message) {
        line.textContent += char;
        scrollTerminalToBottom();
        await wait(10);
    }
}

function addLog(message, type = 'sys-msg') {
    logQueue = logQueue.then(() => typeLogLine(message, type));
    return logQueue;
}

function clearTerminal() {
    const terminal = document.getElementById('sysTerminal');
    if (terminal) terminal.innerHTML = '';
    logQueue = Promise.resolve();
    logCounter = 0;
}

function loadLogs(force = false) {
    if (terminalLoaded && !force) return;
    terminalLoaded = true;
    clearTerminal();
    [
        ['> system.boot()', 'sys-info'],
        ['[ok] UI session initialized', 'sys-msg'],
        ['[ok] price matrix loaded', 'sys-msg'],
        ['[ok] contact terminal attached', 'sys-msg'],
        ['[wait] fill the form to continue', 'sys-info']
    ].forEach(([message, type]) => addLog(message, type));
}

function formatUzPhone(value) {
    const digits = String(value || '').replace(/\D/g, '');
    let normalized = digits;

    if (normalized.startsWith('998')) {
        normalized = normalized.slice(0, 12);
    } else if (normalized.startsWith('8')) {
        normalized = ('99' + normalized).slice(0, 12);
    } else {
        normalized = ('998' + normalized).slice(0, 12);
    }

    if (!normalized.startsWith('998')) {
        normalized = '998';
    }

    const rest = normalized.slice(3);
    const parts = [];
    if (rest.length > 0) parts.push(rest.slice(0, 2));
    if (rest.length > 2) parts.push(rest.slice(2, 5));
    if (rest.length > 5) parts.push(rest.slice(5, 7));
    if (rest.length > 7) parts.push(rest.slice(7, 9));

    return '+998' + (parts.length ? ' ' + parts.filter(Boolean).join(' ') : '');
}

